using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading.Tasks;
using Autodesk.DataExchange.Core.Enums;
using Autodesk.DataExchange.DataModels;
using Autodesk.DataExchange.Interface;
using ConsoleConnector.Driver;
using ConsoleConnector.Common;

namespace ConsoleConnector.Samples
{
    /// <summary>
    /// What you learn: How geometry identity works: your SourceId vs the SDK's UniqueId, and how to find live geometry without downloading it.
    /// SDK: CreatePrimitiveGeometry / CreateMeshGeometry / CreateFileGeometry (sourceId), IElementGeometry.UniqueId + SourceId,
    /// ElementDataModel.GetGeometryMetaDataById, GeometryMetaData, GeometryType.
    /// Console plumbing: GeometrySampleHelper.BeginAsync, PickOrCreateElementAsync, FindAssetFile.
    /// Prerequisites: 2.3 Load Exchange.
    /// </summary>
    [SampleAddress(4, 5, 12)]
    public sealed class FindGeometryBySourceIdSample : ISample
    {
        public string Name => "Find Geometry by SourceId";
        public string Description => "Tag geometry with your own SourceId and look it up as GeometryMetaData";

        public async Task RunAsync(SampleContext ctx)
        {
            var session = await GeometrySampleHelper.BeginAsync(ctx);
            if (session == null)
                return;
            var element = await GeometrySampleHelper.PickOrCreateElementAsync(ctx, session.Model);
            if (element == null)
                return;

            var model = session.Model;
            var prefix = Prompt.AskString("SourceId prefix", $"src-{Guid.NewGuid():N}"[..10]);

            TerminalUi.Info("Every Create*Geometry factory takes an optional sourceId: your connector's own id for the geometry.");
            var geometries = new List<IElementGeometry>
            {
                // SDK: tag a primitive and a mesh with your own ids
                GeometrySampleHelper.CreateTaggedLineGeometry($"{prefix}-line"),
                ElementDataModel.CreateMeshGeometry(
                    GeometrySampleHelper.CreateSampleMesh(),
                    "Tagged mesh",
                    GeometrySampleHelper.DefaultUnits,
                    $"{prefix}-mesh"),
            };

            var stepPath = GeometrySampleHelper.FindAssetFile("box.stp");
            if (stepPath != null)
            {
                // SDK: file geometry accepts the same sourceId argument
                geometries.Add(ElementDataModel.CreateFileGeometry(
                    stepPath,
                    GeometryFormat.Step,
                    GeometrySampleHelper.DefaultRenderStyle,
                    GeometrySampleHelper.DefaultUnits,
                    $"{prefix}-step"));
            }

            TerminalUi.Info("UniqueId is generated by the SDK and is the key for UpdateElementGeometry / DeleteElementGeometry. SourceId is only for lookup.");
            TerminalUi.WriteTable(
                "Created geometries",
                geometries,
                ("SourceId (yours)", g => g.SourceId ?? string.Empty),
                ("UniqueId (SDK)", g => g.UniqueId ?? string.Empty));

            // SDK: attach them to the element
            model.AddElementGeometry(element, geometries);

            TerminalUi.Info("GetGeometryMetaDataById returns identity, name and GeometryType (BRep / Mesh / Primitive) without downloading the payload.");
            foreach (var geometry in geometries)
            {
                // SDK: element-scoped lookup by SourceId
                var found = model.GetGeometryMetaDataById(geometry.SourceId, element).ToList();
                GeometrySampleHelper.PrintGeometryMetaData($"Lookup '{geometry.SourceId}' on {element.Name}", found);
            }

            TerminalUi.Info("Pass element = null to search model-level (exchange root) geometry instead of an element.");
            // SDK: model-level lookup; element geometry is not returned here
            var modelLevel = model.GetGeometryMetaDataById($"{prefix}-line").ToList();
            TerminalUi.Chat($"  Model-level matches for '{prefix}-line': {modelLevel.Count}");

            TerminalUi.Success($"Attached {geometries.Count} tagged geometries to {element.Name} ({element.SourceId}).");
            if (!await ElementSampleHelper.SyncAsync(ctx, session))
                return;

            TerminalUi.Info("UniqueId and SourceId stay stable across sync, so the same lookup still works afterwards.");
            var afterSync = model.GetGeometryMetaDataById($"{prefix}-line", element).ToList();
            GeometrySampleHelper.PrintGeometryMetaData($"Lookup '{prefix}-line' after sync", afterSync);
        }
    }
}
